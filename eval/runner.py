def make_png(w: int, h: int, rgb: tuple[int, int, int], nonce: str = "") -> bytes:
    raw = b"".join(b"\x00" + bytes(rgb) * w for _ in range(h))

    def chunk(tag: bytes, data: bytes) -> bytes:
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw))
            + chunk(b"tEXt", f"nonce\x00{nonce}".encode())
            + chunk(b"IEND", b""))


def make_zip(nonce: str) -> bytes:
    import io

    bio = io.BytesIO()
    with zipfile.ZipFile(bio, "w") as z:
        z.writestr("note.txt", f"eval fixture {nonce}")
    return bio.getvalue()


def materialize(manifest: dict, into: Path) -> dict[str, Path]:
    """Write fixture media (generated bytes ONLY) into the watched folder;
    return fixture_id -> path. Names carry the fixture id and a run nonce so
    discovery is unambiguous and the sweep can clean them up."""
    paths: dict[str, Path] = {}
    for f in manifest["fixtures"]:
        nonce = f["id"]
        if f["generator"] == "png_solid":
            data = make_png(f["width"], f["height"], tuple(f["rgb"]), nonce)
            path = into / f"{f['id']}.png"
        elif f["generator"] == "zip_note":
            data = make_zip(nonce)
            path = into / f"{f['id']}.zip"
        else:
            raise ValueError(f"unknown generator {f['generator']}")
        path.write_bytes(data)
        paths[f["id"]] = path
    return paths


def sweep_generated(into: Path, fixture_paths: dict[str, Path]) -> list[str]:
    removed = []
    for p in fixture_paths.values():
        try:
            p.unlink()
            removed.append(p.name)
        except FileNotFoundError:  # pragma: no cover
            pass
    return removed


async def discover_ids(client, folder_id: int, wanted: dict[str, Path],
                       timeout_s: float = 60.0) -> dict[str, int]:
    """fixture_id -> provider file id, via the inventory route, polling the
    real watcher. Timeout surfaces as a missing id (tracked, not fatal)."""
    deadline = time.time() + timeout_s
    found: dict[str, int] = {}
    while time.time() < deadline and len(found) < len(wanted):
        entries = client.folder_entries(folder_id, limit=100)
        by_name = {e["name"]: e["file_id"] for e in entries.items}
        for fid, path in wanted.items():
            if fid not in found and path.name in by_name:
                found[fid] = by_name[path.name]
        if len(found) < len(wanted):
            await asyncio.sleep(1.0)
    return found


def rank_for_search(items: list[dict], id_by_fixture: dict[str, int]) -> list[tuple[str, int]]:
    """(asset_ref, rank) list from provider items, ranked 1..n."""
    out = []
    fixture_by_id = {v: k for k, v in id_by_fixture.items()}
    for i, item in enumerate(items):
        ref = fixture_by_id.get(item["file_id"], f"unlabeled:{item['file_id']}")
        out.append((ref, i + 1))
    return out
