"""Bridge evaluation CLI (B-14).

  uv run python -m eval.run --manifest eval/manifest.example.json \
      --provider http://127.0.0.1:18765 --watched-dir DIR \
      --managed-folder-id ID --data-dir DIR --out reports/eval-run [--keep]

DIRs are throwaway dirs this CLI owns (fixture materialization + bridge
sqlite); the watched DIR must be the folder the operator registered with
watch on and managed-folder-id pointing at it. Nothing else is touched.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

# pythonpath=["src"] is a pytest setting; as a CLI we add it ourselves
# (repo-local eval tool, no install step needed for measurement runs).
_SRC = Path(__file__).resolve().parent.parent / "src"
if str(_SRC) not in sys.path:
    sys.path.insert(0, str(_SRC))


from eval import runner as R
from eval.metrics import K, mrr_at_10, ndcg_at_10, percentiles, recall_at_10


def _git_commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True,
                              text=True, check=True).stdout.strip()[:12]
    except Exception:
        return "unknown"


def _bridge_commit() -> str:
    return _git_commit()


def verify_real_model(status: dict, expected_revision: str) -> None:
    """Fail before evaluating if the provider is fake, wrong or unidentified."""
    model = status.get("model") or {}
    if (model.get("id") != "google/embeddinggemma-2"
            or model.get("revision") != expected_revision
            or model.get("state") != "ready"
            or expected_revision in ("", "fake")):
        raise ValueError("real EmbeddingGemma 2 model revision did not match the requested pin")


async def _run(args: argparse.Namespace) -> dict:
    from bridge.client import LocalSearchClient
    from bridge.config import validate_config
    from bridge.repository import Repository, open_repository
    from bridge.server import BridgeContext, create_server
    from tests.unit.test_server_health import connected_client

    manifest = json.loads(Path(args.manifest).read_text())
    work = Path(args.data_dir)
    work.mkdir(mode=0o700, parents=True, exist_ok=True)
    cfg = validate_config(data_dir=work / "bdata",
                          provider_base_url=args.provider)
    client = LocalSearchClient(cfg)
    st = client.status()
    if args.expect_model_revision:
        verify_real_model(st, args.expect_model_revision)
    repo = Repository(open_repository(work / "bdata"))
    env = {
        "bridge_commit": _bridge_commit(),
        "provider_version": st.get("version"),
        "provider_generation": (st.get("index") or {}).get("generation"),
        "embedder": (
            # /api/status's model.id says the configured model even when
            # the server runs the deterministic FAKE embedder (revision
            # field reads "fake" — that is the honest signal, docs/15).
            "fake" if (st.get("model") or {}).get("revision") == "fake"
            else (st.get("model") or {}).get("id", "unknown")),
        "device": (st.get("model") or {}).get("device"),
        "model_revision": (st.get("model") or {}).get("revision"),
        "executed_at": datetime.now(timezone.utc).isoformat(),
        "warmup": args.warmup,
        "note": ("fixture media generated by the eval CLI itself; "
                 "qrels by construction (no human labeling)"),
    }

    limitations = [
        "qrels are by construction (generated fixtures + declared links), so "
        "scores measure plumbing correctness, NOT semantic embedding quality",
        ("embedder is the FAKE embedder" if env["embedder"] == "fake"
         else "single model/revision; no paired comparison performed"),
        "no CPersona server involved: memory_to_image runs against the "
        "Bridge's own link table with synthetic mem: refs",
    ]

    fixture_paths = R.materialize(manifest, Path(args.watched_dir))
    ids = await R.discover_ids(client, args.managed_folder_id, fixture_paths)
    missing_ids = [f["id"] for f in manifest["fixtures"] if f["id"] not in ids]

    ctx = BridgeContext(config=cfg, provider=client, db=repo)
    asset_id_by_fixture: dict[str, str] = {}
    tasks: dict[str, dict] = {}
    per_query: list[dict] = []

    async with connected_client(create_server(ctx)) as session:
        # link manifest qrels -> their scoped refs so each task sees its
        # qrels through the product surface only (search_assets/list answer
        # LINKED scoped assets; unlinked fixtures are invisible by design).
        for case in manifest["cases"]:
            memory_ref = case["query"].get("memory_ref")
            if memory_ref is None:
                continue  # image_to_image links nothing (query IS the image)
            for rel in case["relevant"]:
                fid = rel["asset_ref"]
                if fid not in ids:
                    continue
                r_link = await session.call_tool(
                    "link_asset",
                    {"agent_id": case["scope"]["agent_id"],
                     "memory_ref": memory_ref,
                     "provider_file_id": ids[fid],
                     "project_id": case["scope"].get("project_id", ""),
                     "channel": case["scope"].get("channel", "")})
                sc_link = r_link.structured_content or {}
                if sc_link.get("ok") and sc_link.get("asset_id"):
                    asset_id_by_fixture[fid] = sc_link["asset_id"]

        for task_name in ("text_to_image", "memory_to_image", "image_to_image"):
            cases = [c for c in manifest["cases"] if c["task"] == task_name]
            latencies: list[float] = []
            ndcgs, recalls, successes, mrrs = [], [], [], []
            errors = missing_qrels = 0
            # docs/07 §latency warmup: before sampling, run UNTIMED priming
            # queries of the same task path through the same connection.
            if task_name == "text_to_image":
                for _ in range(max(0, args.warmup)):
                    await session.call_tool(
                        "search_assets",
                        {"agent_id": "eval-warmup", "query": "warmup",
                         "limit": 1})
            elif task_name == "memory_to_image":
                for _ in range(max(0, args.warmup)):
                    await session.call_tool(
                        "list_memory_assets",
                        {"agent_id": "eval-warmup",
                         "memory_ref": "mem:0"})
            else:
                warm_probe = next(iter(fixture_paths.values()), None)
                for _ in range(max(0, args.warmup)):
                    if warm_probe is not None:
                        try:
                            client.search_media(
                                warm_probe.read_bytes(),
                                filename="warmup.png",
                                folder_id=args.managed_folder_id,
                                page_size=20)
                        except Exception:  # noqa: BLE001 - priming, failures irrelevant
                            pass
            for case in cases:
                qrels = {r["asset_ref"]: r["grade"]
                         for r in case["relevant"] if r["grade"] > 0}
                if not qrels:
                    # excluded from scoring (docs/07: a case with no graded
                    # qrels must never be scored 0 — it inflates nothing and
                    # hides nothing)
                    missing_qrels += 1
                    continue
                if any(ref not in ids for ref in qrels):
                    errors += 1
                    per_query.append({
                        "case_id": case["id"], "task": task_name,
                        "ranks": [], "errors": ["qrel_fixture_unindexed"],
                        "latency_ms": 0.0, "misranked_into_top10": [],
                    })
                    continue
                t0 = time.perf_counter()
                ranks: list[tuple[str, int]] = []
                case_errors: list[str] = []
                try:
                    if task_name == "text_to_image":
                        res = await session.call_tool(
                            "search_assets",
                            {"agent_id": case["scope"]["agent_id"],
                             "project_id": case["scope"].get("project_id", ""),
                             "channel": case["scope"].get("channel", ""),
                             "query": case["query"]["text"],
                             "limit": 10})
                        sc = res.structured_content or {}
                        if not sc.get("ok"):
                            case_errors.append(
                                (sc.get("error") or {}).get("code", "error"))
                        else:
                            # search_assets answers LINKED scoped assets
                            # only; eval scopes see exactly what they linked
                            for i, e in enumerate(sc.get("results", [])):
                                ranks.append((f"file:{e['provider_file_id']}",
                                              i + 1))
                    elif task_name == "memory_to_image":
                        res = await session.call_tool(
                            "list_memory_assets",
                            {"agent_id": case["scope"]["agent_id"],
                             "project_id": case["scope"].get("project_id", ""),
                             "channel": case["scope"].get("channel", ""),
                             "memory_ref": case["query"]["memory_ref"]})
                        sc = res.structured_content or {}
                        if not sc.get("ok"):
                            case_errors.append(
                                (sc.get("error") or {}).get("code", "error"))
                        else:
                            # docs/04: list_memory_assets answers asset_id/
                            # label/status — NO provider file id (public IF
                            # discipline). memory_to_image qrels therefore
                            # key by asset id, resolved through the link
                            # calls the runner itself made (same scope).
                            for i, e in enumerate(sc.get("assets", [])):
                                ranks.append((f"asset:{e['asset_id']}",
                                              i + 1))
                    else:  # image_to_image via provider attachment route
                        fid = case["query"]["fixture"]
                        if fid not in ids:
                            case_errors.append("fixture_unindexed")
                        else:
                            png = fixture_paths[fid].read_bytes()
                            data = client.search_media(png, filename=f"{fid}.png",
                                                       folder_id=args.managed_folder_id,
                                                       page_size=20)
                            for i, item in enumerate(data.get("items", [])):
                                ranks.append((f"file:{item['file_id']}", i + 1))
                except Exception as exc:  # noqa: BLE001 - eval records any failure as code
                    case_errors.append(getattr(exc, "code", exc.__class__.__name__))
                dt = (time.perf_counter() - t0) * 1000.0
                if case_errors:
                    errors += 1
                    per_query.append({
                        "case_id": case["id"], "task": task_name,
                        "ranks": [], "errors": case_errors,
                        "latency_ms": round(dt, 2),
                        "misranked_into_top10": [],
                    })
                    continue  # API failures are not retrieval misses or measured NDCG=0
                latencies.append(dt)
                # map file:<id> ranks back to fixture ids for qrels
                id_to_fixture = {v: k for k, v in ids.items()}

                fixture_by_asset = {v: k for k, v in asset_id_by_fixture.items()}

                def _ref(raw: str) -> str:
                    if raw.startswith("file:"):
                        tail = raw[5:]
                        if tail.isdigit():
                            return id_to_fixture.get(int(tail), raw)
                    if raw.startswith("asset:"):
                        return fixture_by_asset.get(raw[6:], raw)
                    return raw

                named = [(_ref(ref), rk) for ref, rk in ranks]
                top10 = named[:K]
                grades_in_order = [qrels.get(ref, 0) for ref, _ in top10]
                relevant_total = len(qrels)
                found = sum(1 for ref, _ in top10 if ref in qrels)
                first_rel = next((rk for ref, rk in top10 if ref in qrels), None)
                try:
                    ndcgs.append(ndcg_at_10(grades_in_order, list(qrels.values())))
                    recalls.append(recall_at_10(found, relevant_total))
                    successes.append(1.0 if found else 0.0)
                    mrrs.append(mrr_at_10(first_rel))
                except ValueError:
                    errors += 1
                unlabeled = [ref for ref, _ in top10 if ref not in qrels]
                per_query.append({
                    "case_id": case["id"], "task": task_name,
                    "ranks": [{"asset_ref": ref, "rank": rk,
                               "grade": qrels.get(ref)} for ref, rk in named[:K]],
                    "errors": case_errors, "latency_ms": round(dt, 2),
                    "misranked_into_top10": unlabeled,
                })
            p50, p95 = percentiles(latencies)
            mean = lambda xs: (sum(xs) / len(xs)) if xs else None  # noqa: E731
            tasks[task_name] = {
                "query_count": len(cases),
                "missing_qrels": missing_qrels,
                "errors": errors,
                "status": ("unmeasured" if not ndcgs else
                           "partial" if errors or missing_qrels else "measured"),
                "metrics": {
                    "ndcg_at_10": round(mean(ndcgs), 4) if ndcgs else None,
                    "recall_at_10": round(mean(recalls), 4) if recalls else None,
                    "success_at_10": round(mean(successes), 4) if successes else None,
                    "mrr_at_10": round(mean(mrrs), 4) if mrrs else None,
                    "p50_ms": round(p50, 1) if p50 is not None else None,
                    "p95_ms": round(p95, 1) if p95 is not None else None,
                },
            }

    if missing_ids:
        limitations.append(
            f"{len(missing_ids)} fixture(s) were never indexed by the watcher: "
            + ", ".join(missing_ids))
    if not args.keep:
        R.sweep_generated(Path(args.watched_dir), fixture_paths)
        limitations.append("fixtures were swept (--keep was not passed); "
                           "rerun regenerates them deterministically")
    repo.close()
    client.close()
    return {"schema_version": 1, "env": env, "tasks": tasks,
            "per_query": per_query, "limitations": limitations}


def write_report(result: dict, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "result.json").write_text(
        json.dumps(result, ensure_ascii=False, indent=2))
    lines = ["# Bridge evaluation report (B-14)", "",
             f"- bridge `{result['env']['bridge_commit']}` / provider "
             f"`{result['env']['provider_version']}` / embedder "
             f"`{result['env']['embedder']}` / generation "
             f"`{result['env']['provider_generation']}`",
             f"- executed {result['env']['executed_at']}; warmup "
             f"{result['env']['warmup']}", "",
             "| task | status | NDCG@10 | Recall@10 | Success@10 | MRR@10 | p50 | p95 | errors |",
             "|---|---|---|---|---|---|---|---|---|"]
    for name, t in result["tasks"].items():
        m = t["metrics"]
        cell = lambda v: "—" if v is None else v  # noqa: E731
        lines.append(
            f"| {name} | {t['status']} | {cell(m['ndcg_at_10'])} | "
            f"{cell(m['recall_at_10'])} | {cell(m['success_at_10'])} | "
            f"{cell(m['mrr_at_10'])} | {cell(m['p50_ms'])} | "
            f"{cell(m['p95_ms'])} | {t['errors']} |")
    lines += ["", "## Limitations / unmeasured", ""]
    lines += [f"- {x}" for x in result["limitations"]]
    lines += ["", "Per-query detail: `result.json` (ranks, grades, errors, "
              "misranked_into_top10).", ""]
    (out_dir / "report.md").write_text("\n".join(lines))


def _run_async(args: argparse.Namespace) -> dict:
    return asyncio.run(_run(args))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="bridge-eval")
    ap.add_argument("--manifest", required=True)
    ap.add_argument("--provider", required=True)
    ap.add_argument("--watched-dir", required=True)
    ap.add_argument("--managed-folder-id", type=int, required=True)
    ap.add_argument("--data-dir", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--warmup", type=int, default=3)
    ap.add_argument("--expect-model-revision", default=None,
                    help="fail unless /api/status has real google/embeddinggemma-2 at this exact revision")
    ap.add_argument("--keep", action="store_true",
                    help="keep fixture media in the watched folder")
    args = ap.parse_args(argv)
    result = _run_async(args)
    out_dir = Path(args.out)
    write_report(result, out_dir)
    print(f"wrote {out_dir / 'result.json'} and {out_dir / 'report.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
